def prepare_network(nodes: pd.DataFrame, links: pd.DataFrame) -> Dict[str, Any]:
    node_ids = np.asarray(
        sorted(pd.to_numeric(nodes["node_id"], errors="raise").astype(np.int64)),
        dtype=np.int64,
    )
    n = len(node_ids)
    node_to_idx = {int(x): i for i, x in enumerate(node_ids)}

    work = links[["link_id", "from_node", "to_node", "length_m"]].copy()
    work["link_id"] = pd.to_numeric(work["link_id"], errors="raise").astype(np.int64)
    work["from_node"] = pd.to_numeric(work["from_node"], errors="raise").astype(np.int64)
    work["to_node"] = pd.to_numeric(work["to_node"], errors="raise").astype(np.int64)
    work["length_m"] = pd.to_numeric(work["length_m"], errors="raise").astype(float)
    if work["link_id"].duplicated().any():
        raise ValueError("link.csv contains duplicate link_id values.")
    if np.any(~np.isfinite(work["length_m"])) or np.any(work["length_m"] <= 0):
        raise ValueError("All length_m values must be finite and positive.")

    work["u_idx"] = work["from_node"].map(node_to_idx)
    work["v_idx"] = work["to_node"].map(node_to_idx)
    if work[["u_idx", "v_idx"]].isna().any().any():
        raise ValueError("link.csv references node IDs absent from node.csv.")
    work["u_idx"] = work["u_idx"].astype(np.int32)
    work["v_idx"] = work["v_idx"].astype(np.int32)
    work["_pos"] = np.arange(len(work), dtype=np.int32)

    link_ids = work["link_id"].to_numpy(dtype=np.int64)
    link_lengths = work["length_m"].to_numpy(dtype=np.float64)
    link_id_to_pos = {int(x): i for i, x in enumerate(link_ids)}

    pair_rows: List[int] = []
    pair_cols: List[int] = []
    pair_link_positions: List[np.ndarray] = []
    pair_lookup: Dict[Tuple[int, int], int] = {}

    for p, ((u, v), grp) in enumerate(work.groupby(["u_idx", "v_idx"], sort=True)):
        grp = grp.sort_values(["length_m", "link_id"])
        pair_rows.append(int(u))
        pair_cols.append(int(v))
        positions = grp["_pos"].to_numpy(dtype=np.int32)
        pair_link_positions.append(positions)
        pair_lookup[(int(u), int(v))] = int(p)

    pair_rows_arr = np.asarray(pair_rows, dtype=np.int32)
    pair_cols_arr = np.asarray(pair_cols, dtype=np.int32)
    base_weights = np.asarray(
        [link_lengths[int(pos[0])] for pos in pair_link_positions],
        dtype=np.float64,
    )
    base_adj = csr_matrix(
        (base_weights, (pair_rows_arr, pair_cols_arr)),
        shape=(n, n),
        dtype=np.float64,
    )

    return {
        "n": int(n),
        "node_ids": node_ids,
        "node_to_idx": node_to_idx,
        "link_ids": link_ids,
        "link_lengths": link_lengths,
        "link_id_to_pos": link_id_to_pos,
        "pair_rows": pair_rows_arr,
        "pair_cols": pair_cols_arr,
        "pair_link_positions": tuple(pair_link_positions),
        "pair_lookup": pair_lookup,
        "base_weights": base_weights,
        "base_adj": base_adj,
        "n_links": int(len(link_ids)),
    }


def lscc_share(adj: csr_matrix, n_total: int) -> float:
    if n_total <= 0:
        return 0.0
    n_comp, labels = connected_components(
        adj, directed=True, connection="strong", return_labels=True
    )
    if labels.size == 0:
        return 0.0
    counts = np.bincount(labels, minlength=n_comp)
    return float(counts.max() / n_total)


