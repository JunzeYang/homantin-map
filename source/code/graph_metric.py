def init_worker(
    n: int,
    pair_rows: np.ndarray,
    pair_cols: np.ndarray,
    pair_link_positions: Tuple[np.ndarray, ...],
    base_weights: np.ndarray,
    link_ids: np.ndarray,
    link_lengths: np.ndarray,
    node_ids: np.ndarray,
    sources: np.ndarray,
    od_origin_idx: np.ndarray,
    od_destination_idx: np.ndarray,
    od_demand: np.ndarray,
    od_baseline_distance: np.ndarray,
    base_eff: float,
    base_total_distance: float,
    disconnect_penalty_m: float,
    base_lscc: float,
) -> None:
    global _W
    _W = {
        "n": int(n),
        "pair_rows": np.asarray(pair_rows, dtype=np.int32),
        "pair_cols": np.asarray(pair_cols, dtype=np.int32),
        "pair_link_positions": tuple(np.asarray(x, dtype=np.int32) for x in pair_link_positions),
        "base_weights": np.asarray(base_weights, dtype=np.float64),
        "link_ids": np.asarray(link_ids, dtype=np.int64),
        "link_lengths": np.asarray(link_lengths, dtype=np.float64),
        "link_id_to_pos": {int(x): i for i, x in enumerate(link_ids)},
        "node_ids": np.asarray(node_ids, dtype=np.int64),
        "node_id_to_idx": {int(x): i for i, x in enumerate(node_ids)},
        "sources": np.asarray(sources, dtype=np.int32),
        "source_row": {int(x): i for i, x in enumerate(sources)},
        "od_origin_idx": np.asarray(od_origin_idx, dtype=np.int32),
        "od_destination_idx": np.asarray(od_destination_idx, dtype=np.int32),
        "od_demand": np.asarray(od_demand, dtype=np.float64),
        "od_baseline_distance": np.asarray(od_baseline_distance, dtype=np.float64),
        "base_eff": float(base_eff),
        "base_total_distance": float(base_total_distance),
        "disconnect_penalty_m": float(disconnect_penalty_m),
        "base_lscc": float(base_lscc),
        "n_links": int(len(link_ids)),
    }


def adjacency_after_one_link(link_id: int) -> csr_matrix:
    pos_remove = _W["link_id_to_pos"][int(link_id)]
    rows = _W["pair_rows"]
    cols = _W["pair_cols"]
    groups = _W["pair_link_positions"]
    lengths = _W["link_lengths"]

    weights = np.empty(len(groups), dtype=np.float64)
    keep = np.zeros(len(groups), dtype=bool)
    for p, positions in enumerate(groups):
        chosen = -1
        for pos in positions:
            if int(pos) != int(pos_remove):
                chosen = int(pos)
                break
        if chosen >= 0:
            weights[p] = lengths[chosen]
            keep[p] = True
    return csr_matrix(
        (weights[keep], (rows[keep], cols[keep])),
        shape=(_W["n"], _W["n"]),
        dtype=np.float64,
    )


def adjacency_after_one_node(node_id: int) -> csr_matrix:
    idx = _W["node_id_to_idx"][int(node_id)]
    rows = _W["pair_rows"]
    cols = _W["pair_cols"]
    keep = (rows != idx) & (cols != idx)
    return csr_matrix(
        (_W["base_weights"][keep], (rows[keep], cols[keep])),
        shape=(_W["n"], _W["n"]),
        dtype=np.float64,
    )


def worker_state_metrics(adj: csr_matrix, demand_affected: bool) -> Tuple[float, float, float, float]:
    scc = lscc_share(adj, _W["n"])
    lscc_loss = (
        (_W["base_lscc"] - scc) / _W["base_lscc"]
        if _W["base_lscc"] > 0
        else np.nan
    )
    if abs(lscc_loss) < 1e-12:
        lscc_loss = 0.0

    if not demand_affected:
        return 0.0, float(lscc_loss), 0.0, 1.0

    dist = dijkstra(
        adj, directed=True, indices=_W["sources"], return_predecessors=False
    )
    if dist.ndim == 1:
        dist = dist.reshape(1, -1)

    src_rows = np.asarray(
        [_W["source_row"][int(x)] for x in _W["od_origin_idx"]], dtype=np.int32
    )
    dst = _W["od_destination_idx"]
    q = _W["od_demand"]
    d0 = _W["od_baseline_distance"]
    ds = dist[src_rows, dst]
    reachable = np.isfinite(ds) & (ds > 0)
    q_total = float(q.sum(dtype=np.float64))
    q_reach = float(q[reachable].sum(dtype=np.float64))

    eff = (
        float(np.sum(q[reachable] / ds[reachable], dtype=np.float64) / q_total)
        if q_total > 0
        else 0.0
    )
    eff_loss = (
        (_W["base_eff"] - eff) / _W["base_eff"]
        if _W["base_eff"] > 0
        else np.nan
    )
    if abs(eff_loss) < 1e-12:
        eff_loss = 0.0

    penalized = np.where(reachable, ds, d0 + _W["disconnect_penalty_m"])
    total_distance = float(np.sum(q * penalized, dtype=np.float64))
    td_loss = (
        (total_distance - _W["base_total_distance"]) / _W["base_total_distance"]
        if _W["base_total_distance"] > 0
        else np.nan
    )
    if abs(td_loss) < 1e-12:
        td_loss = 0.0

    reach_share = float(q_reach / q_total) if q_total > 0 else np.nan
    return float(eff_loss), float(lscc_loss), float(td_loss), reach_share


def eval_link_chunk(tasks: Sequence[Tuple[int, bool]]) -> List[Tuple[int, float, float, float, float]]:
    rows = []
    for link_id, affected in tasks:
        adj = adjacency_after_one_link(int(link_id))
        e, s, td, r = worker_state_metrics(adj, bool(affected))
        rows.append((int(link_id), e, s, td, r))
    return rows


def eval_node_chunk(tasks: Sequence[Tuple[int, bool]]) -> List[Tuple[int, float, float, float, float]]:
    rows = []
    for node_id, affected in tasks:
        adj = adjacency_after_one_node(int(node_id))
        e, s, td, r = worker_state_metrics(adj, bool(affected))
        rows.append((int(node_id), e, s, td, r))
    return rows


def chunks(values: Sequence[Any], n_chunks_hint: int) -> List[List[Any]]:
    vals = list(values)
    if not vals:
        return []
    n_chunks_hint = max(1, min(int(n_chunks_hint), len(vals)))
    size = int(math.ceil(len(vals) / n_chunks_hint))
    return [vals[i : i + size] for i in range(0, len(vals), size)]


def evaluate_components(
    component: str,
    tasks: Sequence[Tuple[int, bool]],
    parallel: bool,
    workers: int,
    initargs: Tuple[Any, ...],
) -> List[Tuple[int, float, float, float, float]]:
    fn = eval_link_chunk if component == "link" else eval_node_chunk
    task_chunks = chunks(tasks, workers * 8 if parallel else 1)
    if not parallel or workers <= 1:
        init_worker(*initargs)
        rows = []
        iterator = task_chunks
        if tqdm is not None:
            iterator = tqdm(iterator, desc=component + " removals", unit="chunk")
        for chunk in iterator:
            rows.extend(fn(chunk))
        return rows

    rows = []
    with ProcessPoolExecutor(
        max_workers=workers, initializer=init_worker, initargs=initargs
    ) as ex:
        futures = [ex.submit(fn, chunk) for chunk in task_chunks]
        iterator = as_completed(futures)
        if tqdm is not None:
            iterator = tqdm(
                iterator, total=len(futures), desc=component + " removals", unit="chunk"
            )
        for fut in iterator:
            rows.extend(fut.result())
    return rows


