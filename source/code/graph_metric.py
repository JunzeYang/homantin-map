"""OD-aware criticality metrics for the directed road network.

Required upstream files
-----------------------
    node.csv
    link.csv
    res/od/od_connector.csv       <- generated by od_prepare.py

Node and directed-link metrics (same four dimensions for both)
---------------------------------------------------------------
1. ``odbc``
   OD-weighted shortest-path load centrality (betweenness-style). Connector OD
   demand is assigned to distance-shortest directed paths. Road nodes on the
   selected path, including road access endpoints, receive the OD demand. For
   parallel minimum-length links, demand is divided equally among tied links.

2. ``od_eff_loss``
   Relative loss of demand-weighted network efficiency after isolated removal:

       E_OD = sum(q_rs / d_rs) / sum(q_rs)
       loss = (E0 - E_removed) / E0

   Baseline-unreachable connector OD is excluded consistently from all
   demand-based metrics. Newly unreachable OD contributes zero to E_OD.

3. ``lscc_loss``
   Relative loss of the largest strongly connected component (LSCC) share.
   This remains deliberately topological and is not OD weighted.

4. ``td_loss``
   Demand-weighted total-distance loss after isolated removal. To keep this
   metric finite when an OD becomes disconnected, a newly unreachable OD is
   assigned a transparent, data-derived disruption penalty:

       disrupted distance = baseline distance + D_penalty
       D_penalty = maximum finite baseline connector-OD distance

   The script also reports ``unreachable_demand_share`` as a diagnostic so the
   penalty is never hidden.

All route costs are ``length_m`` only. No free-flow speed, capacity, BPR, or UE
assignment is used.

Outputs
-------
    res/graph_metric/node_metric.csv
    res/graph_metric/link_metric.csv
    res/graph_metric/summary.csv
    res/graph_metric/metric_meta.json
    res/graph_metric/cache/od_active.csv
    res/graph_metric/cache/node_index.csv

Examples
--------
    python code/graph_metric.py
    python code/graph_metric.py --workers 6
    python code/graph_metric.py --no-parallel
    python code/graph_metric.py --test-components 30
"""

