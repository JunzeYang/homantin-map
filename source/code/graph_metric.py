def od_state_metrics_from_distances(
    distances: np.ndarray,
    active_od: pd.DataFrame,
    source_row: Dict[int, int],
    baseline_total_distance: float,
    disconnect_penalty_m: float,
) -> Dict[str, float]:
    src_rows = np.asarray(
        [source_row[int(x)] for x in active_od["origin_idx"]], dtype=np.int32
    )
    dst = active_od["destination_idx"].to_numpy(dtype=np.int32)
    q = active_od["demand"].to_numpy(dtype=np.float64)
    d0 = active_od["baseline_distance_m"].to_numpy(dtype=np.float64)
    ds = distances[src_rows, dst]

    reachable = np.isfinite(ds) & (ds > 0)
    q_total = float(q.sum(dtype=np.float64))
    q_reach = float(q[reachable].sum(dtype=np.float64))

    efficiency = (
        float(np.sum(q[reachable] / ds[reachable], dtype=np.float64) / q_total)
        if q_total > 0
        else 0.0
    )

    penalized = np.where(reachable, ds, d0 + float(disconnect_penalty_m))
    total_distance = float(np.sum(q * penalized, dtype=np.float64))
    td_loss = (
        (total_distance - baseline_total_distance) / baseline_total_distance
        if baseline_total_distance > 0
        else float("nan")
    )
    if abs(td_loss) < 1e-12:
        td_loss = 0.0

    return {
        "od_eff": efficiency,
        "penalized_total_distance": total_distance,
        "td_loss": float(td_loss),
        "reachable_demand_share": float(q_reach / q_total) if q_total > 0 else np.nan,
    }


