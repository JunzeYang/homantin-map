def prepare_od(od: pd.DataFrame, network: Dict[str, Any]) -> pd.DataFrame:
    require_columns(od, ["origin_node", "destination_node", "demand"], "od_connector.csv")
    out = od[["origin_node", "destination_node", "demand"]].copy()
    out["origin_node"] = pd.to_numeric(out["origin_node"], errors="raise").astype(np.int64)
    out["destination_node"] = pd.to_numeric(out["destination_node"], errors="raise").astype(np.int64)
    out["demand"] = pd.to_numeric(out["demand"], errors="coerce").astype(float)
    out = out[np.isfinite(out["demand"]) & (out["demand"] > 0)].copy()
    out = out[out["origin_node"] != out["destination_node"]].copy()

    valid_nodes = set(int(x) for x in network["node_ids"])
    bad = (~out["origin_node"].isin(valid_nodes)) | (~out["destination_node"].isin(valid_nodes))
    if bad.any():
        raise ValueError("OD connector table references road nodes absent from node.csv.")

    # Aggregate identical road-node pairs to reduce repeated extraction work.
    out = (
        out.groupby(["origin_node", "destination_node"], as_index=False)["demand"]
        .sum()
        .sort_values(["origin_node", "destination_node"])
        .reset_index(drop=True)
    )
    out["origin_idx"] = out["origin_node"].map(network["node_to_idx"]).astype(np.int32)
    out["destination_idx"] = out["destination_node"].map(network["node_to_idx"]).astype(np.int32)
    return out


def baseline_od_shortest_paths(
    od: pd.DataFrame,
    network: Dict[str, Any],
) -> Tuple[pd.DataFrame, np.ndarray, np.ndarray, np.ndarray, Dict[int, int]]:
    sources = np.sort(od["origin_idx"].unique().astype(np.int32))
    source_row = {int(s): i for i, s in enumerate(sources)}
    print("Computing baseline OD-source directed shortest paths (%d sources)..." % len(sources))
    dist, pred = dijkstra(
        network["base_adj"],
        directed=True,
        indices=sources,
        return_predecessors=True,
    )
    if dist.ndim == 1:
        dist = dist.reshape(1, -1)
        pred = pred.reshape(1, -1)

    rows = np.asarray([source_row[int(x)] for x in od["origin_idx"]], dtype=np.int32)
    dst = od["destination_idx"].to_numpy(dtype=np.int32)
    d0 = dist[rows, dst]
    active = np.isfinite(d0) & (d0 > 0)

    out = od.loc[active].copy().reset_index(drop=True)
    out["baseline_distance_m"] = d0[active].astype(float)
    out.insert(0, "active_od_id", np.arange(len(out), dtype=np.int64))
    if out.empty:
        raise RuntimeError("No connector OD pair is reachable on the directed road network.")

    return out, sources, dist, pred, source_row


def reconstruct_path(pred_row: np.ndarray, source: int, target: int) -> Optional[List[int]]:
    if source == target:
        return [int(source)]
    path = [int(target)]
    cur = int(target)
    seen = {cur}
    max_steps = len(pred_row) + 2
    for _ in range(max_steps):
        p = int(pred_row[cur])
        if p == PRED_NULL or p < 0:
            return None
        path.append(p)
        if p == source:
            path.reverse()
            return path
        if p in seen:
            return None
        seen.add(p)
        cur = p
    return None


def compute_odbc(
    active_od: pd.DataFrame,
    pred: np.ndarray,
    source_row: Dict[int, int],
    network: Dict[str, Any],
) -> Tuple[np.ndarray, np.ndarray, Dict[str, float]]:
    node_load = np.zeros(network["n"], dtype=np.float64)
    link_load = np.zeros(network["n_links"], dtype=np.float64)
    total_q = float(active_od["demand"].to_numpy(dtype=np.float64).sum(dtype=np.float64))
    failures = 0

    link_lengths = network["link_lengths"]
    link_ids = network["link_ids"]

    iterator = active_od.itertuples(index=False)
    if tqdm is not None:
        iterator = tqdm(iterator, total=len(active_od), desc="OD path loading", unit="OD")

    for row in iterator:
        s = int(row.origin_idx)
        t = int(row.destination_idx)
        q = float(row.demand)
        prow = pred[source_row[s]]
        path = reconstruct_path(prow, s, t)
        if path is None or len(path) < 2:
            failures += 1
            continue

        # Connector road nodes are real road-network access locations. They are
        # included in load centrality because zone endpoints themselves are not
        # graph nodes; this avoids artificially assigning zero importance to an
        # access node whose removal affects its represented demand.
        node_load[np.asarray(path, dtype=np.int32)] += q

        for u, v in zip(path[:-1], path[1:]):
            p = network["pair_lookup"].get((int(u), int(v)))
            if p is None:
                failures += 1
                continue
            positions = network["pair_link_positions"][int(p)]
            min_len = float(link_lengths[int(positions[0])])
            tied = [
                int(pos)
                for pos in positions
                if abs(float(link_lengths[int(pos)]) - min_len) <= 1e-9
            ]
            share = q / max(1, len(tied))
            for pos in tied:
                link_load[pos] += share

    if failures:
        warnings.warn("%d path-loading predecessor/edge inconsistencies detected." % failures)

    if total_q > 0:
        node_odbc = node_load / total_q
        link_odbc = link_load / total_q
    else:
        node_odbc = node_load
        link_odbc = link_load

    stats = {
        "active_demand": total_q,
        "node_load_sum": float(node_load.sum(dtype=np.float64)),
        "link_load_sum": float(link_load.sum(dtype=np.float64)),
        "path_loading_failures": int(failures),
    }
    return node_odbc, link_odbc, stats


