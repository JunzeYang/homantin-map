def build_summary(node_result: pd.DataFrame, link_result: pd.DataFrame, baseline: Dict[str, float]) -> pd.DataFrame:
    rows: List[Dict[str, Any]] = []

    def add(entity: str, metric: str, s: pd.Series) -> None:
        x = pd.to_numeric(s, errors="coerce").replace([np.inf, -np.inf], np.nan).dropna()
        if x.empty:
            return
        for stat, val in [
            ("min", x.min()),
            ("median", x.median()),
            ("p90", x.quantile(0.90)),
            ("p95", x.quantile(0.95)),
            ("max", x.max()),
        ]:
            rows.append({"entity": entity, "metric": metric, "stat": stat, "value": float(val)})

    for metric in ("odbc", "od_eff_loss", "lscc_loss", "td_loss"):
        add("node", metric, node_result[metric])
        add("link", metric, link_result[metric])
    for k, v in baseline.items():
        if isinstance(v, (int, float, np.integer, np.floating)):
            rows.append({"entity": "network", "metric": k, "stat": "value", "value": float(v)})
    return pd.DataFrame(rows)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--parallel", dest="parallel", action="store_true")
    group.add_argument("--no-parallel", dest="parallel", action="store_false")
    parser.set_defaults(parallel=DEFAULT_PARALLEL)
    parser.add_argument("--workers", type=int, default=DEFAULT_WORKERS)
    parser.add_argument(
        "--test-components",
        type=int,
        default=0,
        help="evaluate first N links/nodes only; 0 = all",
    )
    return parser.parse_args()


# =============================================================================
# Main
# =============================================================================

def main() -> int:
    args = parse_args()
    started = time.perf_counter()
    workers = max(1, int(args.workers))
    parallel = bool(args.parallel and workers > 1)

    RESULT_DIR.mkdir(parents=True, exist_ok=True)
    CACHE_DIR.mkdir(parents=True, exist_ok=True)

    required = [NODE_PATH, LINK_PATH, OD_PATH]
    missing = [str(p) for p in required if not p.exists()]
    if missing:
        raise FileNotFoundError(
            "Missing inputs: %s. Run net.py (if needed) and od_prepare.py first." % missing
        )

    nodes, node_enc = read_csv_auto(NODE_PATH)
    links, link_enc = read_csv_auto(LINK_PATH)
    od_raw, od_enc = read_csv_auto(OD_PATH)
    require_columns(nodes, ["node_id", "lon", "lat"], "node.csv")
    require_columns(links, ["link_id", "from_node", "to_node", "length_m"], "link.csv")

    nodes = nodes.copy()
    links = links.copy()
    nodes["node_id"] = pd.to_numeric(nodes["node_id"], errors="raise").astype(np.int64)
    links["link_id"] = pd.to_numeric(links["link_id"], errors="raise").astype(np.int64)
    links["from_node"] = pd.to_numeric(links["from_node"], errors="raise").astype(np.int64)
    links["to_node"] = pd.to_numeric(links["to_node"], errors="raise").astype(np.int64)
    links["length_m"] = pd.to_numeric(links["length_m"], errors="raise").astype(float)

    network = prepare_network(nodes, links)
    od = prepare_od(od_raw, network)
    print("Loaded %d nodes, %d directed links, %d aggregated connector OD pairs." % (
        len(nodes), len(links), len(od)
    ))

    node_index = pd.DataFrame({
        "index": np.arange(network["n"], dtype=np.int32),
        "node_id": network["node_ids"],
    })
    node_index.to_csv(NODE_INDEX_OUT, index=False, encoding="utf-8-sig")

    active_od, sources, dist0, pred0, source_row = baseline_od_shortest_paths(od, network)
    raw_q = float(od["demand"].to_numpy(dtype=np.float64).sum(dtype=np.float64))
    active_q = float(active_od["demand"].to_numpy(dtype=np.float64).sum(dtype=np.float64))
    active_od[[
        "active_od_id", "origin_node", "destination_node", "origin_idx",
        "destination_idx", "demand", "baseline_distance_m"
    ]].to_csv(OD_ACTIVE_OUT, index=False, encoding="utf-8-sig")

    q = active_od["demand"].to_numpy(dtype=np.float64)
    d0 = active_od["baseline_distance_m"].to_numpy(dtype=np.float64)
    base_eff = float(np.sum(q / d0, dtype=np.float64) / q.sum(dtype=np.float64))
    base_total_distance = float(np.sum(q * d0, dtype=np.float64))
    disconnect_penalty_m = float(np.max(d0))
    base_lscc = lscc_share(network["base_adj"], network["n"])

    node_odbc, link_odbc, load_stats = compute_odbc(
        active_od, pred0, source_row, network
    )

    node_odbc_map = {
        int(network["node_ids"][i]): float(node_odbc[i])
        for i in range(network["n"])
    }
    link_odbc_map = {
        int(network["link_ids"][i]): float(link_odbc[i])
        for i in range(network["n_links"])
    }

    initargs = (
        network["n"],
        network["pair_rows"],
        network["pair_cols"],
        network["pair_link_positions"],
        network["base_weights"],
        network["link_ids"],
        network["link_lengths"],
        network["node_ids"],
        sources,
        active_od["origin_idx"].to_numpy(dtype=np.int32),
        active_od["destination_idx"].to_numpy(dtype=np.int32),
        active_od["demand"].to_numpy(dtype=np.float64),
        active_od["baseline_distance_m"].to_numpy(dtype=np.float64),
        base_eff,
        base_total_distance,
        disconnect_penalty_m,
        base_lscc,
    )

    link_ids = [int(x) for x in network["link_ids"]]
    node_ids = [int(x) for x in network["node_ids"]]
    if int(args.test_components) > 0:
        k = int(args.test_components)
        warnings.warn("TEST MODE: evaluating first %d links and first %d nodes." % (k, k))
        link_ids = link_ids[:k]
        node_ids = node_ids[:k]

    # A positive-length shortest path can only worsen after removing a component
    # that lies on at least one selected baseline shortest path. Components with
    # zero ODBC therefore skip repeated OD Dijkstra while still receiving exact
    # LSCC loss. This is exact for the selected deterministic shortest paths;
    # equal-length parallel links already share ODBC and are recomputed.
    link_tasks = [(lid, link_odbc_map.get(lid, 0.0) > 0.0) for lid in link_ids]
    node_tasks = [(nid, node_odbc_map.get(nid, 0.0) > 0.0) for nid in node_ids]

    print(
        "Evaluating isolated removals: parallel=%s, workers=%d, OD-active links=%d/%d, nodes=%d/%d"
        % (
            parallel,
            workers if parallel else 1,
            sum(a for _, a in link_tasks), len(link_tasks),
            sum(a for _, a in node_tasks), len(node_tasks),
        )
    )
    t_rem = time.perf_counter()
    link_eval = evaluate_components("link", link_tasks, parallel, workers, initargs)
    node_eval = evaluate_components("node", node_tasks, parallel, workers, initargs)
    removal_seconds = time.perf_counter() - t_rem

    # Assemble node results.
    node_keep = [c for c in ["node_id", "osm_id", "lon", "lat"] if c in nodes.columns]
    node_result = nodes[node_keep].copy()
    node_result["odbc"] = node_result["node_id"].map(node_odbc_map).fillna(0.0).astype(float)
    node_eval_df = pd.DataFrame(
        node_eval,
        columns=["node_id", "od_eff_loss", "lscc_loss", "td_loss", "reachable_demand_share"],
    )
    node_result = node_result.merge(node_eval_df, on="node_id", how="left")

    # Assemble link results.
    keep_cols = [c for c in (
        "link_id", "from_node", "to_node", "u_osm", "v_osm", "edge_key",
        "osm_way", "name", "highway", "oneway", "length_m", "lanes",
        "maxspeed", "ref", "access", "bridge", "tunnel", "geometry"
    ) if c in links.columns]
    link_result = links[keep_cols].copy()
    link_result["odbc"] = link_result["link_id"].map(link_odbc_map).fillna(0.0).astype(float)
    link_eval_df = pd.DataFrame(
        link_eval,
        columns=["link_id", "od_eff_loss", "lscc_loss", "td_loss", "reachable_demand_share"],
    )
    link_result = link_result.merge(link_eval_df, on="link_id", how="left")

    # In test mode, unevaluated components stay NaN except ODBC. In full mode,
    # every component must have all isolated-removal metrics.
    if int(args.test_components) <= 0:
        req = ["od_eff_loss", "lscc_loss", "td_loss", "reachable_demand_share"]
        if node_result[req].isna().any().any() or link_result[req].isna().any().any():
            raise RuntimeError("Missing isolated-removal metric in full run.")

    for df in (node_result, link_result):
        for col in ("od_eff_loss", "lscc_loss", "td_loss"):
            bad = df[col] < -1e-8
            if bad.fillna(False).any():
                warnings.warn("Negative %s values detected; inspect numerical/data consistency." % col)
            tiny = df[col].abs() < 1e-12
            df.loc[tiny.fillna(False), col] = 0.0
        add_rank_columns(df, "odbc", "odbc")
        add_rank_columns(df, "od_eff_loss", "od_eff")
        add_rank_columns(df, "lscc_loss", "lscc")
        add_rank_columns(df, "td_loss", "td")

    node_result.to_csv(NODE_OUT, index=False, encoding="utf-8-sig")
    link_result.to_csv(LINK_OUT, index=False, encoding="utf-8-sig")

    baseline = {
        "n_nodes": int(network["n"]),
        "n_directed_links": int(network["n_links"]),
        "raw_connector_demand": raw_q,
        "active_connector_demand": active_q,
        "baseline_reachable_demand_share": active_q / raw_q if raw_q > 0 else np.nan,
        "od_efficiency": base_eff,
        "lscc_share": base_lscc,
        "total_distance_m_trip": base_total_distance,
        "disconnect_penalty_m": disconnect_penalty_m,
        "active_od_pairs": int(len(active_od)),
        "od_source_nodes": int(len(sources)),
    }
    build_summary(node_result, link_result, baseline).to_csv(
        SUMMARY_OUT, index=False, encoding="utf-8-sig"
    )

    runtime = time.perf_counter() - started
    meta = {
        "input": {
            "node_csv": str(NODE_PATH),
            "link_csv": str(LINK_PATH),
            "od_connector_csv": str(OD_PATH),
            "node_encoding": node_enc,
            "link_encoding": link_enc,
            "od_encoding": od_enc,
        },
        "graph": {
            "nodes": int(network["n"]),
            "directed_links": int(network["n_links"]),
            "unique_ordered_node_pairs": int(len(network["pair_rows"])),
            "weight": "length_m",
            "directed": True,
            "parallel_links": True,
        },
        "metrics": {
            "common_node_link_metrics": [
                "odbc", "od_eff_loss", "lscc_loss", "td_loss"
            ],
            "odbc": (
                "OD-weighted distance-shortest-path load / total active OD demand; "
                "road access endpoint nodes included; tied minimum parallel links split equally"
            ),
            "od_eff_loss": (
                "relative loss of sum(q/d)/sum(q) after isolated removal"
            ),
            "lscc_loss": "relative loss of largest strongly connected component share",
            "td_loss": (
                "relative increase of demand-weighted total distance; newly unreachable "
                "OD assigned baseline distance + max baseline OD distance"
            ),
            "unreachable_diagnostic": "reachable_demand_share is saved for every isolated removal",
        },
        "baseline": baseline,
        "od_path_loading": load_stats,
        "runtime_seconds": {
            "isolated_removals": float(removal_seconds),
            "total": float(runtime),
        },
        "parallel": {"enabled": parallel, "workers": workers if parallel else 1},
        "outputs": {
            "node_metric": str(NODE_OUT),
            "link_metric": str(LINK_OUT),
            "summary": str(SUMMARY_OUT),
            "active_od": str(OD_ACTIVE_OUT),
            "node_index": str(NODE_INDEX_OUT),
        },
        "test_components": int(args.test_components),
        "seed": MASTER_SEED,
    }
    META_OUT.write_text(json.dumps(meta, ensure_ascii=False, indent=2), encoding="utf-8")

    print("\nCompleted OD-aware graph metrics.")
    print(f"  Baseline active OD demand: {active_q:,.2f} ({100.0 * baseline['baseline_reachable_demand_share']:.2f}% of mapped road-proxy demand)")
    print("  OD efficiency: %.10g 1/m" % base_eff)
    print("  LSCC share: %.6f" % base_lscc)
    print(f"  Total weighted distance: {base_total_distance:,.3f} m-trip")
    print("  Disconnection penalty: %.1f m" % disconnect_penalty_m)
    print("  Runtime: %.1f s" % runtime)
    print("  Saved: %s" % RESULT_DIR)
    return 0


